def main():
    items = json.load(open(RAW_PATH, encoding="utf-8"))
    out = []
    for idx, item in enumerate(items):
        ov = OVERRIDES.get(idx)
        if ov:
            if ov.get("drop"):
                continue
            item = dict(item)
            item["name"] = ov.get("name", item["name"])
            item["desc"] = ov.get("desc", item["desc"])
            if "cat" in ov:
                item["cat"] = ov["cat"]
        out.append(item)

    # финальная проверка на оставшиеся длинные "слипшиеся" имена
    still_broken = [i for i in out if len(i["name"].split()) > 5]
    print(f"Осталось {len(out)} мест (было {len(items)}), из них подозрительных длинных имён: {len(still_broken)}")
    for i in still_broken:
        print("  ?", i["city"], "|", i["name"][:80])

    json.dump(out, open(OUT_PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"-> {OUT_PATH}")


if __name__ == "__main__":
    main()
